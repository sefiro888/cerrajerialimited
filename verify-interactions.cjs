const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
let submit;
const fields=new Map([['service','Copia o programación de llaves'],['car','SEAT León'],['year','2019'],['location','Guadalajara'],['message','¿Podéis hacer una segunda llave?']]);
const form={reportValidity:()=>true};
const sandbox={document:{querySelector(selector){if(selector==='#quote-form')return {addEventListener(_,fn){submit=fn;}};return null;},addEventListener(){}},window:{addEventListener(){},location:{href:''}},FormData:class{get(key){return fields.get(key);}},encodeURIComponent};
vm.runInNewContext(fs.readFileSync('dist/assets/app.js','utf8'),sandbox);
let prevented=false;
submit({preventDefault(){prevented=true;},currentTarget:form});
assert(prevented);
const url=new URL(sandbox.window.location.href);
assert.equal(url.host,'wa.me');
assert.equal(url.pathname,'/34672826060');
const message=url.searchParams.get('text');
assert(message.includes('SEAT León (2019)'));
assert(message.includes('Guadalajara'));
assert(message.includes('¿Podéis hacer una segunda llave?'));
sandbox.window.location.href='';
form.reportValidity=()=>false;
submit({preventDefault(){},currentTarget:form});
assert.equal(sandbox.window.location.href,'');
console.log('OK: WhatsApp message preserves Spanish characters and vehicle details; invalid form does not navigate. No messages sent.');
